#!/usr/bin/env node
/**
 * Generate src/build-info.ts before tsc runs so the running server can report
 * its own identity via get_session. Used to detect stale-build sessions: if
 * the agent rebuilt but Claude Desktop is still serving the old process, the
 * build_time in get_session will pre-date the rebuild.
 *
 * Run via the `build:server` and `dev` scripts. Safe to run standalone.
 */

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');

function gitTry(cmd, fallback) {
  try {
    return execSync(cmd, { cwd: repo, encoding: 'utf8' }).trim();
  } catch {
    return fallback;
  }
}

const pkg = JSON.parse(readFileSync(resolve(repo, 'package.json'), 'utf8'));
const buildSha = gitTry('git rev-parse --short HEAD', 'unknown');
const gitDirty = gitTry('git status --porcelain', '').length > 0;
const buildTime = new Date().toISOString();
const serverVersion = pkg.version ?? '0.0.0';

const banner =
  '/**\n' +
  ' * AUTO-GENERATED by scripts/write-build-info.mjs — do not edit by hand.\n' +
  ' * Regenerated on every `npm run build:server` (and `npm run dev`).\n' +
  ' * Tracked in git so a fresh clone typechecks; treat local changes here\n' +
  ' * as build artefacts (commit only when intentional).\n' +
  ' */\n';

const body =
  `export const BUILD_INFO = {\n` +
  `  server_version: ${JSON.stringify(serverVersion)},\n` +
  `  build_sha: ${JSON.stringify(buildSha)},\n` +
  `  build_time: ${JSON.stringify(buildTime)},\n` +
  `  git_dirty: ${JSON.stringify(gitDirty)},\n` +
  `} as const;\n`;

writeFileSync(resolve(repo, 'src/build-info.ts'), banner + body);
console.log(`wrote src/build-info.ts (${buildSha}${gitDirty ? '-dirty' : ''} @ ${buildTime})`);
